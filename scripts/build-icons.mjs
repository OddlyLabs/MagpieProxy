// Rebuild the small offline icon bundle from the pinned official Lucide SVGs.
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
const root = new URL("../", import.meta.url)
const manifest = JSON.parse(readFileSync(new URL("vendor/lucide/manifest.json", root), "utf8"))
const definitions = {}
for (const name of new Set(Object.values(manifest.aliases))) {
  const svg = readFileSync(new URL(`vendor/lucide/icons/${name}.svg`, root), "utf8")
  definitions[name] = [...svg.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)\/?\s*>/g)].map(([, tag, attrs]) => [tag, Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, key, value]) => [key, value]))])
  if (!definitions[name].length) throw new Error(`No shapes in ${name}`)
}
const code = `// Lucide ${manifest.version}, ISC. Generated by scripts/build-icons.mjs; see vendor/lucide/LICENSE.
globalThis.EgressIcons = (() => {
  const aliases = ${JSON.stringify(manifest.aliases)}
  const icons = ${JSON.stringify(definitions)}
  const create = (name, size = 16) => {
    const key = aliases[name] || name, shapes = icons[key]
    if (!shapes) throw new Error("Unknown Lucide icon: " + name)
    const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg")
    for (const [attr, value] of Object.entries({ viewBox: "0 0 24 24", width: size, height: size, fill: "none", stroke: "currentColor", "stroke-width": 1.75, "stroke-linecap": "round", "stroke-linejoin": "round", "aria-hidden": "true", focusable: "false", "data-lucide": key })) svg.setAttribute(attr, value)
    for (const [tag, attrs] of shapes) {
      const shape = document.createElementNS(svg.namespaceURI, tag)
      for (const [attr, value] of Object.entries(attrs)) shape.setAttribute(attr, value)
      svg.append(shape)
    }
    return svg
  }
  return Object.freeze({ create })
})()
`
writeFileSync(new URL("page/icons.js", root), code)
const original = readFileSync(new URL(`vendor/lucide/icons/${manifest.aliases.logo}.svg`, root), "utf8")
const logo = original.replace('stroke="currentColor"', 'stroke="#6b687b"').replace('stroke-width="2"', 'stroke-width="1.75"').replace(/(<svg\b[^>]*>)/, '$1\n  <style>@media(prefers-color-scheme:dark){svg{stroke:#b7b1cb}}</style>')
writeFileSync(new URL("page/icon.svg", root), logo)
const path = new URL("package.json", root), pkg = JSON.parse(readFileSync(path, "utf8"))
pkg.magpie.icon = "data:image/svg+xml;base64," + Buffer.from(logo).toString("base64")
if (!pkg.files.includes("page/icons.js")) pkg.files.splice(pkg.files.indexOf("page/model.js"), 0, "page/icons.js")
writeFileSync(path, JSON.stringify(pkg, null, 2) + "\n")
console.log(`Built ${Object.keys(definitions).length} Lucide icons in ${fileURLToPath(new URL("page/icons.js", root))}`)
