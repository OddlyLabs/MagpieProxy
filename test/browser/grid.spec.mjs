import { test, expect } from "@playwright/test"
import axe from "axe-core"

for (const [width, theme] of [[320, "light"], [375, "dark"], [768, "light"], [1280, "dark"], [1440, "light"]]) {
  test(`multi-column ${width}px ${theme} shows more accounts at the same font size`, async ({ page }) => {
    const errors = []; page.on("pageerror", (error) => errors.push(error.message))
    await page.setViewportSize({ width, height: 900 }); await page.goto(`/?scenario=large&theme=${theme}`)
    await page.getByLabel("筛选供应商").selectOption("zcode")
    const standardFont = await page.locator(".account-name").first().evaluate((node) => getComputedStyle(node).fontSize)
    await page.getByRole("button", { name: "紧凑视图", exact: true }).click()
    const visible = () => page.locator(".account-row").evaluateAll((rows) => rows.filter((row) => { const bounds = row.getBoundingClientRect(); return bounds.top >= 0 && bounds.bottom <= innerHeight }).length)
    const compactCount = await visible()
    await page.getByRole("button", { name: "多列视图", exact: true }).click()
    await expect(page.locator(".account-card")).toHaveCount(96)
    expect(await page.locator(".account-name").first().evaluate((node) => getComputedStyle(node).fontSize)).toBe(standardFont)
    expect(await visible()).toBeGreaterThan(compactCount)
    const columns = await page.locator(".account-grid").evaluate((node) => getComputedStyle(node).gridTemplateColumns.split(" ").length)
    expect(columns).toBeGreaterThanOrEqual(2)
    if (width <= 375) expect(columns).toBe(2)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole("button", { name: /再显示 96 个账号/ }).click()
    await expect(page.locator(".account-card")).toHaveCount(192)
    await page.getByRole("searchbox", { name: "搜索账号、节点或 IP" }).fill("alex+999@")
    await expect(page.locator(".account-card")).toHaveCount(1)
    await page.reload()
    await expect(page.getByRole("button", { name: "多列视图", exact: true })).toHaveAttribute("aria-pressed", "true")
    expect(errors).toEqual([])
  })
}

test("multi-column cards retain IP copy, local proxy copy, details and confirmed node changes", async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 900 }); await page.goto("/")
  await page.getByRole("button", { name: "多列视图", exact: true }).click()
  await page.evaluate(() => { Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText: async (text) => { window.__copied = text } } }) })
  await page.getByRole("button", { name: "复制出口 IP 198.51.100.11", exact: true }).click()
  expect(await page.evaluate(() => window.__copied)).toBe("198.51.100.11")
  await page.getByRole("button", { name: "复制 工作账号 01 的本地代理地址", exact: true }).click()
  expect(await page.evaluate(() => window.__copied)).toBe("socks5://127.0.0.1:17901")
  await page.getByRole("button", { name: "查看 工作账号 01 的账号详情", exact: true }).click()
  await expect(page.getByRole("dialog")).toContainText("socks5://127.0.0.1:17901")
  await page.keyboard.press("Escape")
  await page.getByRole("button", { name: "为 工作账号 01 换绑节点", exact: true }).click()
  const dialog = page.getByRole("dialog")
  await dialog.getByRole("searchbox", { name: "搜索节点", exact: true }).fill("HK-HongKong-05")
  await dialog.locator(".node-option").click()
  expect(await page.evaluate(() => window.__previewRequests.filter((request) => request.action !== "page-seen"))).toEqual([])
  await dialog.getByRole("button", { name: "确认换绑", exact: true }).click()
  await expect(page.locator("#task-banner")).toBeHidden({ timeout: 6000 })
  await expect(page.locator(".account-card").first()).toContainText("HK-HongKong-05")
})

for (const theme of ["light", "dark"]) test(`multi-column ${theme} uses accessible lists with no WCAG violations`, async ({ page }) => {
  await page.goto(`/?theme=${theme}`)
  await page.getByRole("button", { name: "多列视图", exact: true }).click()
  await expect(page.getByRole("list", { name: "ZCode 出口分配", exact: true }).getByRole("listitem")).toHaveCount(8)
  await page.evaluate(axe.source)
  const violations = await page.evaluate(async () => (await axe.run(document, { runOnly: { type: "tag", values: ["wcag2a", "wcag2aa", "wcag21aa"] } })).violations.map((item) => ({ id: item.id, nodes: item.nodes.map((node) => node.target) })))
  expect(violations).toEqual([])
})
